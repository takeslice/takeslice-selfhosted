#!/bin/sh
# Create a .env with a random database password and application secrets.
# Usage: ./scripts/init-env.sh [app-url]
set -eu

cd "$(dirname "$0")/.."

if [ -f .env ]; then
  echo ".env already exists. Move it aside first if you want a new one." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate secrets." >&2
  exit 1
fi

APP_URL="${1:-http://localhost:3000}"
case "$APP_URL" in
  *[!A-Za-z0-9:/._~-]*)
    echo "APP_URL contains characters that are not safe in a .env file." >&2
    exit 1
    ;;
esac

# URL-safe so the password can be embedded in DATABASE_URL and Compose values.
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
BETTER_AUTH_SECRET="$(openssl rand -base64 32 | tr -d '\n')"
ENCRYPTION_KEY="$(openssl rand -base64 32 | tr -d '\n')"

umask 077
cat > .env <<EOF
# Generated by scripts/init-env.sh. Keep this file private and out of version control.

POSTGRES_USER=takeslice
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_DB=takeslice

# Inside Docker Compose the database host is "db". For local development change
# it to localhost:5432 and use the same password.
DATABASE_URL=postgres://takeslice:$POSTGRES_PASSWORD@db:5432/takeslice

APP_URL=$APP_URL
APP_PORT=3000

BETTER_AUTH_SECRET=$BETTER_AUTH_SECRET
ENCRYPTION_KEY=$ENCRYPTION_KEY

# Optional. When unset, the first-run setup token is printed to the app logs.
SETUP_TOKEN=

PORT=3000
TRUST_PROXY=false
LOG_LEVEL=info
EOF

echo "Wrote .env with a generated database password and application secrets."
echo "Next: docker compose up -d"
